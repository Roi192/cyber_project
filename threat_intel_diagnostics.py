#   THREAT_INTEL_DIAG_USE_OS_TRUST_STORE=true
# before running "test"/"test-all-keyless" if real connection tests fail
# with SSLCertVerificationError on this machine - see the dedicated
# comment further down for why (local antivirus HTTPS-scanning feature,
# not a network block). Never disables certificate verification; only
# widens the trusted-root set. Not needed on a normal Linux deployment.
#
# SAFETY GUARANTEES:
#   - "status" never performs a network call and never writes anything -
#     it is the exact same read-only query as /threat-intel's provider
#     status table (threat_intel_display.provider_status_table()).
#   - "test"/"test-all-keyless" NEVER write to the live cybersec.db: this
#     script redirects SOC_DB_PATH to a dedicated, separate file
#     (data/threat_intel_diagnostics.db - never cybersec.db) BEFORE
#     importing anything else, unless the caller has already set
#     SOC_DB_PATH explicitly (e.g. to run this inside an isolated test).
#   - A live test is only ever attempted for a provider that is EITHER
#     already configured (a key is present) OR doc-confirmed keyless
#     (same requires_api_key=False providers as the UI's manual re-check -
#     see threat_intel_display.force_recheck). A provider needing a key
#     it does not have is reported "NOT CONFIGURED - no live test
#     attempted", never silently skipped without explanation.
#   - Only a well-known, generic, non-sensitive public test indicator is
#     ever sent (8.8.8.8 / example.com / https://www.google.com/ / the
#     SHA-256 and MD5 of the empty string) - never organizational data.
#   - NEVER prints an API key value, header, or raw response body -
#     only status/boolean/error-class fields, same discipline as every
#     provider adapter's own logging.
# ==================================================

