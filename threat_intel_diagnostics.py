def print_status_table():

    print(f"{'Provider':<22} {'Configured':<12} {'Mode':<10} {'Evidence':<24} {'Match':>6} {'NoMatch':>8} "
          f"{'Error':>6} {'RateLim':>8} {'LastChecked (UTC)'}")
    print("-" * 130)

    for row in threat_intel_display.provider_status_table():

        configured_label = "Yes" if row["configured"] else ("Active*" if not row["requires_api_key"] else "No")
        mode = "Automatic" if row["automatic_eligible"] else ("Manual" if row["manual_eligible"] else "-")
        evidence = "Malicious evidence" if row["evidence_class"] == "malicious_evidence" else "Context only"

        print(f"{row['provider']:<22} {configured_label:<12} {mode:<10} {evidence:<24} "
              f"{row['match_count']:>6} {row['no_match_count']:>8} {row['error_count']:>6} "
              f"{row['rate_limited_count']:>8} {row['last_checked_at'] or 'Never'}")

    print()
    print("* 'Active' = no API key required (doc-confirmed keyless mode: GreyNoise, PhishTank, urlscan.io search).")
    print("  'Context only' providers never independently affect Threat Risk/Alerts/Incidents/Response.")
    print("  This table is READ-ONLY against the live database - no network call was made to produce it.")


def diagnose_one(provider):

    # Returns a result dict; NEVER raises; NEVER prints/logs a key value.
    meta = framework.PROVIDER_REGISTRY.get(provider)

    if meta is None or not meta.get("implemented"):
        return {"provider": provider, "status": "UNKNOWN_PROVIDER"}

    requires_key = bool(meta.get("requires_api_key", True))
    configured = framework.get_provider_configuration_state(provider) == framework.CONFIG_STATE_AVAILABLE

    out = {
        "provider": provider,
        "configured": configured,
        "requires_api_key": requires_key,
        "auth_result": "N/A",
        "response_valid": None,
        "rate_limited": False,
        "error": None,
    }

    if provider in _NOT_LIVE_TESTABLE_HERE:
        out["error"] = f"Not live-tested by this tool: {_NOT_LIVE_TESTABLE_HERE[provider]}"
        return out

    if requires_key and not configured:
        out["error"] = "NOT CONFIGURED - no API key present; no live test attempted."
        return out

    indicator_type, indicator_value = _TEST_INDICATOR.get(provider, (None, None))

    if indicator_type is None:
        out["error"] = "No test indicator defined for this provider."
        return out

    result = threat_intel_display.force_recheck(provider, indicator_type, indicator_value)

    if "error" in result:
        out["error"] = result["error"]
        out["auth_result"] = "ERROR"
        return out

    status = result.get("lookup_status")

    out["response_valid"] = status in ("MATCH", "NO_MATCH")
    out["rate_limited"] = status == "RATE_LIMITED"

    if status in ("MATCH", "NO_MATCH"):
        out["auth_result"] = "SUCCESS"
    elif status == "RATE_LIMITED":
        out["auth_result"] = "RATE_LIMITED"
    else:
        out["auth_result"] = "FAILED"
        # The provider's own sanitized summary (never a raw response body,
        # never a header, never a key - same discipline as every adapter).
        out["error"] = result.get("summary") or "Unspecified connection/authentication failure."

    return out


def print_diagnosis(out):

    print(f"Provider:        {out['provider']}")
    print(f"Configured:      {out.get('configured')}")
    print(f"Auth result:     {out.get('auth_result')}")
    print(f"Valid response:  {out.get('response_valid')}")
    print(f"Rate limited:    {out.get('rate_limited')}")
    print(f"Error:           {out.get('error') or '-'}")
    print()


