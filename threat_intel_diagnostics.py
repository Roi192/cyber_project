# OCT 2026 STEP 16: prepare-otx-ca-bundle
# --------------------------------------------------
# Shows the operator EXACTLY which certificate chain otx.alienvault.com
# actually presents on THIS machine, for manual review, and writes a
# bundle file ONLY on explicit --confirm (never silently, never by
# default). The bundle contains ONLY certifi's existing public roots
# PLUS the specific chain just inspected for this ONE host - never the
# entire Windows certificate store (see otx_provider.py's own comment on
# OTX_CA_BUNDLE for why that distinction matters). Connecting without
# verification here is intentional and safe: the ONLY use of the
# connection is to read the server's already-public certificate chain
# for display and operator review - no request path/body is sent beyond
# the TLS handshake itself, and nothing from this inspection is trusted
# or written anywhere without the operator explicitly reviewing the
# printed chain first.

def _inspect_and_prepare_otx_ca_bundle(confirm, out_path):
    import ssl
    import socket
    import tempfile
    import certifi

    host = "otx.alienvault.com"
    ctx = ssl._create_unverified_context()

    with socket.create_connection((host, 443), timeout=10) as sock:
        with ctx.wrap_socket(sock, server_hostname=host) as ssock:
            chain = ssock.get_unverified_chain()  # list of raw DER bytes, leaf first
            if not chain:
                print(f"[prepare-otx-ca-bundle] no certificate chain was returned by {host} - nothing to do.")
                return 1

            print(f"[prepare-otx-ca-bundle] certificate chain presented by {host} on this machine ({len(chain)} certificate(s)):")
            pem_certs = []
            tmp_path = os.path.join(tempfile.gettempdir(), "otx_chain_inspect.pem")
            for i, der_bytes in enumerate(chain):
                pem = ssl.DER_cert_to_PEM_cert(der_bytes)
                pem_certs.append(pem)
                with open(tmp_path, "w", encoding="utf-8") as f:
                    f.write(pem)
                try:
                    info = ssl._ssl._test_decode_cert(tmp_path)
                    subject = dict(x[0] for x in info.get("subject", ()))
                    issuer = dict(x[0] for x in info.get("issuer", ()))
                except Exception as exc:
                    subject, issuer = {"error": str(exc)}, {}
                print(f"  [{i}] subject={subject}")
                print(f"       issuer ={issuer}")
            if os.path.exists(tmp_path):
                os.remove(tmp_path)

            if not confirm:
                print()
                print("Review the chain above. If (and only if) you recognize and approve trusting it "
                      "(e.g. a known organizational TLS-inspection or antivirus HTTPS-scanning root), "
                      "re-run this command with --confirm to write the bundle file. Nothing was written.")
                return 0

            os.makedirs(os.path.dirname(out_path), exist_ok=True)
            with open(out_path, "w", encoding="utf-8") as f:
                with open(certifi.where(), encoding="utf-8") as cf:
                    f.write(cf.read())
                f.write("\n")
                for pem in pem_certs:
                    f.write(pem)

            print()
            print(f"[prepare-otx-ca-bundle] wrote {out_path} (certifi's public roots + the {len(pem_certs)} "
                  f"certificate(s) reviewed above, for {host} only).")
            print(f"To use it, set in .env:  OTX_CA_BUNDLE={out_path}")
            print("This affects ONLY the AlienVault OTX adapter - no other provider reads this variable.")
            return 0


def main():

    parser = argparse.ArgumentParser(description="Threat Intel per-provider connection diagnostics")
    parser.add_argument("command", choices=("status", "test", "test-all-keyless", "prepare-otx-ca-bundle"))
    parser.add_argument("provider", nargs="?")
    parser.add_argument("--confirm", action="store_true",
                         help="Actually write the OTX CA bundle file (prepare-otx-ca-bundle only) - "
                              "without this flag, the certificate chain is only shown for review.")
    parser.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "otx_ca_bundle.pem"),
                         help="Output path for prepare-otx-ca-bundle (default: data/otx_ca_bundle.pem)")
    args = parser.parse_args()

    if args.command == "prepare-otx-ca-bundle":
        return _inspect_and_prepare_otx_ca_bundle(args.confirm, args.out)

    if args.command == "status":
        print_status_table()
        return 0

    if args.command in ("test", "test-all-keyless"):
        # The isolated diagnostics DB (or whatever SOC_DB_PATH the caller
        # set) may be brand new - ensure the threat_intel_evidence schema
        # exists before any provider tries to read/write it. Idempotent
        # (CREATE TABLE IF NOT EXISTS) - safe to call every run, including
        # against an existing, already-initialized database.
        threat_intel_providers.init_threat_intel_db()

    if args.command == "test":

        if not args.provider:
            print("Usage: python threat_intel_diagnostics.py test <provider>")
            return 2

        if args.provider not in framework.PROVIDER_REGISTRY:
            print(f"Unknown provider: {args.provider}")
            return 2

        print_diagnosis(diagnose_one(args.provider))
        return 0

    if args.command == "test-all-keyless":

        for provider in KEYLESS_PROVIDERS:
            print_diagnosis(diagnose_one(provider))

        return 0


if __name__ == "__main__":
    sys.exit(main())
