# Usage:
#   python threat_intel_diagnostics.py status                  # all 13 providers, config-only, READ-ONLY against
#                                                                # the live database, NO network call
#   python threat_intel_diagnostics.py test <provider>          # ONE real live attempt for a single provider
#   python threat_intel_diagnostics.py test-all-keyless         # ONE real live attempt each for the 3 providers
