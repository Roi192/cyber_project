# ==================================================
# OCT 2026 STEP 15: OPTIONAL OS-TRUST-STORE WIDENING (diagnostic tool
# only - the live provider adapters are NOT changed by this and keep
# using requests/certifi's normal, portable, public-CA-only default,
# which is the correct choice for a real deployment).
# ==================================================
#
# Root cause (diagnosed Step 15, confirmed via direct certificate
# inspection - ssl.create_default_context() against otx.alienvault.com
# on THIS machine): a locally-installed antivirus product's HTTPS-
# scanning feature ("Avast Web/Mail Shield", confirmed by inspecting the
# actual certificate chain presented: issuer "Avast Web/Mail Shield
# Root", OU "generated by Avast Antivirus for SSL/TLS scanning")
# transparently re-signs SOME outbound TLS connections (observed: OTX;
# not observed: google.com) with a root certificate it generates locally
# and installs into the WINDOWS OS trust store. This is a legitimate,
# non-malicious, already OS-trusted local TLS-inspection feature, NOT a
# network-level block and NOT a certificate problem with OTX itself -
# but requests/certifi does not consult the Windows OS store by default,
# only its own bundled list of PUBLIC CAs, so it correctly refuses a
# certificate chain rooted in a CA it has never heard of.
#
# This flag does NOT disable certificate verification - verification
# stays fully ON. It only WIDENS the trusted-root set used for this
# diagnostic run to match what the OS/browser already trust (certifi's
# public roots PLUS the Windows CA/ROOT/AuthRoot certificate stores),
# using only Python's own stdlib ssl.enum_certificates (Windows-only,
# built into CPython - no new pip dependency). Off by default; opt-in
# via THREAT_INTEL_DIAG_USE_OS_TRUST_STORE=true; Windows-only (silently
# has no effect elsewhere); the temp bundle file is created with
# user-only permissions semantics (TEMP dir, removed at exit) and
# contains only public certificate material, never a secret.
_OS_TRUST_STORE_BUNDLE_PATH = None


def _build_os_trust_store_bundle():
    import ssl
    import tempfile
    import certifi

    fd, path = tempfile.mkstemp(prefix="soc_combined_ca_", suffix=".pem")
    with os.fdopen(fd, "wb") as out:
        with open(certifi.where(), "rb") as f:
            out.write(f.read())
        out.write(b"\n")
        added = 0
        for store in ("ROOT", "CA", "AuthRoot"):
            try:
                for cert_der, encoding, _trust in ssl.enum_certificates(store):
                    out.write(ssl.DER_cert_to_PEM_cert(cert_der).encode())
                    added += 1
            except OSError:
                pass  # a store that doesn't exist/isn't readable - skip, never fatal
    return path, added


if sys.platform == "win32" and os.getenv("THREAT_INTEL_DIAG_USE_OS_TRUST_STORE", "").strip().lower() == "true":
    _OS_TRUST_STORE_BUNDLE_PATH, _added_count = _build_os_trust_store_bundle()
    # requests reads REQUESTS_CA_BUNDLE as its default `verify` path for
    # any call that does not pass verify= explicitly (true of every
    # adapter in this project) - this is the standard, documented way to
    # widen trust without touching a single call site.
    os.environ["REQUESTS_CA_BUNDLE"] = _OS_TRUST_STORE_BUNDLE_PATH
    print(f"[diagnostics] OS trust-store widening ENABLED for this run "
          f"(+{_added_count} certs from the Windows CA/ROOT/AuthRoot stores). "
          f"Certificate verification remains fully ON.")

